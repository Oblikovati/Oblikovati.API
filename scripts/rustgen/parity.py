"""Generate fixture registrations; Go's own encoder supplies the expected JSON."""

from pathlib import Path

from names import rust_path, rust_type, snake
from declarations import CUSTOM
from schema import Declaration, Rpc

GO_HEADER = "// SPDX-License-Identifier: Apache-2.0\n// Code generated by scripts/rustgen; DO NOT EDIT.\n\npackage main\n\n"
RS_HEADER = "// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/rustgen; edit the Go contract and run make generate.\n\n"


def generate_parity(
    declarations: list[Declaration], calls: list[Rpc], interfaces: set[tuple[str, str]]
) -> None:
    values = [
        item
        for item in declarations
        if not item.constant
        and item.package != "contract"
        and item.shape.kind != "interface"
    ]
    go_root = Path("go/scripts/apifixtures")
    go_root.mkdir(parents=True, exist_ok=True)
    for old in go_root.glob("registry_*.go"):
        old.unlink()
    groups = [values[index : index + 80] for index in range(0, len(values), 80)]
    for index, group in enumerate(groups):
        write_go_registry(go_root, index, group)
    registry = (
        "var fixtureRegistry = [][]fixtureType{\n"
        + "".join(f"    fixtureGroup{index},\n" for index in range(len(groups)))
        + "}\n"
    )
    (go_root / "registry_all.go").write_text(GO_HEADER + registry)
    write_rust_parity(values)
    write_client_parity(calls, interfaces)
    write_go_calls(calls)
    write_feature_kinds(values)
    write_geometry_contract(values, interfaces)


def write_go_registry(root: Path, index: int, declarations: list[Declaration]) -> None:
    packages = sorted({item.package for item in declarations})
    imports = (
        'import (\n "reflect"\n'
        + "".join(
            f' "oblikovati.org/api/{"wire/featureargs" if package == "featureargs" else package}"\n'
            for package in packages
        )
        + ")\n"
    )
    entries = "".join(
        f'    {{"{item.package}.{item.name}", reflect.TypeFor[{item.package}.{item.name}]()}},\n'
        for item in declarations
    )
    (root / f"registry_{index:03}.go").write_text(
        GO_HEADER
        + imports
        + f"var fixtureGroup{index} = []fixtureType{{\n{entries}}}\n"
    )


def write_rust_parity(values: list[Declaration]) -> None:
    root = Path("rust/tests/parity_generated")
    root.mkdir(parents=True, exist_ok=True)
    for old in root.glob("values_*.rs"):
        old.unlink()
    modules: list[str] = []
    for index in range(0, len(values), 60):
        name = f"values_{index//60:03}"
        chunks = [
            f'#[test]\nfn {item.package}_{snake(item.name)}() {{ super::check::<{rust_path(item.package,item.name).replace("crate::", "oblikovati_api::") }>("{item.package}.{item.name}"); }}\n'
            for item in values[index : index + 60]
        ]
        (root / f"{name}.rs").write_text(RS_HEADER + "\n".join(chunks))
        modules.append(f"mod {name};\n")
    (root / "mod.rs").write_text(
        RS_HEADER + "".join(modules) + "pub(super) use super::check;\n"
    )


def write_client_parity(calls: list[Rpc], interfaces: set[tuple[str, str]]) -> None:
    root = Path("rust/tests/client_generated")
    root.mkdir(parents=True, exist_ok=True)
    for old in root.glob("calls_*.rs"):
        old.unlink()
    modules: list[str] = []
    for index in range(0, len(calls), 20):
        name = f"calls_{index//20:03}"
        content = "\n".join(
            client_test(call, interfaces) for call in calls[index : index + 20]
        )
        (root / f"{name}.rs").write_text(RS_HEADER + content)
        modules.append(f"mod {name};\n")
    (root / "mod.rs").write_text(RS_HEADER + "".join(modules))


def client_test(call: Rpc, interfaces: set[tuple[str, str]]) -> str:
    receiver = "client" if call.group == "Client" else f"client.{snake(call.group)}()"
    request = rust_type(call.request, interfaces).replace("crate::", "oblikovati_api::")
    empty = call.request.kind == "empty"
    argument = "" if empty else "&args"
    args = "" if empty else f"    let args: {request} = Default::default();\n"
    expected = "Vec::new()" if empty else "serde_json::to_vec(&args).unwrap()"
    return (
        f"#[test]\nfn {snake(call.group)}_{snake(call.name)}() {{\n{args}"
        f"    let fake = super::super::RecordingCaller::new(oblikovati_api::wire::{snake(call.method).upper()}, {expected});\n"
        f"    let client = oblikovati_api::client::Client::new(fake);\n"
        f'    assert_eq!({receiver}.{snake(call.name)}({argument}).unwrap_err().0, "recorded");\n}}\n'
    )


def write_go_calls(calls: list[Rpc]) -> None:
    # Private transport helpers have no reflective Go entry point; Rust still tests their wire method.
    calls = [call for call in calls if call.name[0].isupper()]
    root = Path("go/client")
    for old in root.glob("rust_parity_*_test.go"):
        old.unlink()
    for index in range(0, len(calls), 30):
        chunks: list[str] = []
        for call in calls[index : index + 30]:
            chunks.append(
                f"func TestRustParity{call.group}{call.name}(t *testing.T) {{\n"
                f" c := client.New(parityCaller{{t, wire.{call.method}}})\n"
                f' checkGoGroup(t, c, "{call.group}", "{call.name}")\n}}\n'
            )
        imports = 'import ("testing"; "oblikovati.org/api/client"; "oblikovati.org/api/wire")\n\n'
        header = GO_HEADER.replace("package main", "package client_test")
        (root / f"rust_parity_{index//30:03}_test.go").write_text(
            header + imports + "\n".join(chunks)
        )


def write_feature_kinds(values: list[Declaration]) -> None:
    chunks = [
        f"#[test]\nfn {snake(item.name)}() {{\n    use oblikovati_api::wire::featureargs::Arg;\n    assert_eq!(oblikovati_api::wire::featureargs::{item.name}::default().kind(), {item.feature_kind});\n}}\n"
        for item in values
        if item.feature_kind
    ]
    root = Path("rust/tests/feature_kinds")
    root.mkdir(parents=True, exist_ok=True)
    modules: list[str] = []
    for index in range(0, len(chunks), 50):
        name = f"kinds_{index//50:03}"
        (root / f"{name}.rs").write_text(
            RS_HEADER + "\n".join(chunks[index : index + 50])
        )
        modules.append(f"mod {name};\n")
    (root / "mod.rs").write_text(RS_HEADER + "".join(modules))


def write_geometry_contract(
    values: list[Declaration], interfaces: set[tuple[str, str]]
) -> None:
    # Exhaustive construction also checks the fields of types with hand-written JSON codecs.
    chunks: list[str] = []
    for item in values:
        if item.package != "types" or item.name not in CUSTOM or item.name == "Variant":
            continue
        fields = ", ".join(
            f"{snake(field.name)}: <{rust_type(field.shape, interfaces)}>::default()"
            for field in item.shape.fields
        )
        body = f"let _ = oblikovati_api::types::{item.name} {{ {fields} }};"
        chunks.append(
            f"#[test]\nfn {snake(item.name)}_matches_go_fields() {{ {body} }}\n"
        )
    Path("rust/tests/geometry_contract.rs").write_text(RS_HEADER + "\n".join(chunks))
