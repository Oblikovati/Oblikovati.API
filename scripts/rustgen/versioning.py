"""Keep the crate package and ABI handshake on the Go contract version."""

from pathlib import Path
import re


def synchronize_version(root: Path) -> None:
    version_source = (root / "go/version.go").read_text()
    match = re.search(r'const Version = "(\d+)\.(\d+)\.(\d+)"', version_source)
    if match is None:
        raise ValueError(
            f"{version_source!r}: expected const Version with three numeric components"
        )
    version = ".".join(match.groups())
    manifest = root / "rust/Cargo.toml"
    manifest.write_text(
        re.sub(
            r'^version = "[^"]+"',
            f'version = "{version}"',
            manifest.read_text(),
            count=1,
            flags=re.MULTILINE,
        )
    )
    constants = (
        "// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/rustgen from go/version.go.\n\n"
        f'pub const VERSION: &str = "{version}";\n'
        f"pub const API_MAJOR: i32 = {match[1]};\npub const API_MINOR: i32 = {match[2]};\n"
    )
    (root / "rust/src/version.rs").write_text(constants)
