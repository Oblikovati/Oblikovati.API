"""Keep the cross-language corpus in bounded files, included in Cargo-only tests."""

from pathlib import Path


def main() -> None:
    records = Path("build/go-wire.jsonl").read_text().splitlines(keepends=True)
    root = Path("rust/tests/fixtures")
    for old in root.glob("go-wire*.jsonl"):
        old.unlink()
    includes: list[str] = []
    for index in range(0, len(records), 150):
        name = f"go-wire-{index//150:03}.jsonl"
        (root / name).write_text("".join(records[index : index + 150]))
        includes.append(f'    include_str!("{name}"),\n')
    (root / "mod.rs").write_text(
        "// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/split-fixtures.py.\n\npub const CONTENTS: &str = concat!(\n"
        + "".join(includes)
        + ");\n"
    )


if __name__ == "__main__":
    main()
